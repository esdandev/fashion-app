import { readFileSync } from 'node:fs'
import { dirname, extname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { expect, test } from '@playwright/test'
import type { APIRequestContext } from '@playwright/test'

const API_URL = 'http://localhost:5210'
const ADMIN_SECRET = 'test-secret'
const fixturesDir = join(dirname(fileURLToPath(import.meta.url)), 'fixtures')

interface GarmentSeed {
  fixture: string
  name: string
  styleTags: string[]
}

async function archiveGarment(request: APIRequestContext, id: string) {
  const response = await request.delete(`${API_URL}/api/garments/${id}`)
  if (!response.ok()) {
    throw new Error(
      `No se pudo archivar la prenda ${id}: ${response.status()} ${await response.text()}`,
    )
  }
}

/**
 * Seeds a garment through the same analyze + confirm pair the UI uses. The
 * digest test only needs a real garment with style tags, so it skips the
 * upload dialog and talks to the API directly.
 *
 * `camisa-lino.webp` is also an outfits fixture and confirm dedupes by content
 * hash. Archiving a previous row first frees the hash, so this spec always gets
 * the name it asked for instead of the outfit spec's garment (or a retry's).
 */
async function seedGarment(
  request: APIRequestContext,
  seed: GarmentSeed,
): Promise<string> {
  const extension = extname(seed.fixture).toLowerCase()
  const mimeType = extension === '.webp' ? 'image/webp' : 'image/jpeg'

  const analyze = await request.post(`${API_URL}/api/garments/analyze`, {
    multipart: {
      file: {
        name: seed.fixture,
        mimeType,
        buffer: readFileSync(join(fixturesDir, seed.fixture)),
      },
    },
  })

  if (!analyze.ok()) {
    throw new Error(
      `No se pudo analizar ${seed.fixture}: ${analyze.status()} ${await analyze.text()}`,
    )
  }

  const { contentHash, existingGarmentId } = (await analyze.json()) as {
    contentHash: string
    existingGarmentId: string | null
  }

  if (existingGarmentId) {
    await archiveGarment(request, existingGarmentId)
  }

  const confirm = await request.post(`${API_URL}/api/garments/confirm`, {
    data: {
      contentHash,
      name: seed.name,
      category: 'top',
      colorName: 'beige',
      seasons: ['spring', 'summer', 'autumn'],
      formality: 3,
      styleTags: seed.styleTags,
      confidence: 0.9,
    },
  })

  if (!confirm.ok()) {
    throw new Error(
      `No se pudo confirmar ${seed.name}: ${confirm.status()} ${await confirm.text()}`,
    )
  }

  const { garment } = (await confirm.json()) as {
    garment: { id: string }
  }
  return garment.id
}

test('muestra el resumen del día y lo relaciona con una prenda', async ({
  page,
  request,
}) => {
  // Unique per attempt: a CI retry reuses the isolated database and would
  // otherwise find two garments with the same name (ambiguous locator).
  const suffix = `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`
  const garmentName = `Camisa de lino ${suffix}`

  const garmentId = await seedGarment(request, {
    fixture: 'camisa-lino.webp',
    name: garmentName,
    styleTags: ['minimalista'],
  })

  try {
    const refresh = await request.post(`${API_URL}/api/digest/refresh`, {
      headers: { 'X-Admin-Secret': ADMIN_SECRET },
    })

    // A retry runs within the one-hour cooldown: the digest generated by the
    // failed first attempt is still valid and serves the same notes.
    expect([200, 429]).toContain(refresh.status())

    await page.goto('/')

    await expect(page.getByRole('heading', { name: 'Hoy' })).toBeVisible()
    await expect(page.getByText('Resumen de prueba')).toBeVisible()

    const notes = page.getByRole('list', { name: 'Novedades del día' })
    const externalLink = notes.getByRole('link').first()
    await expect(externalLink).toHaveAttribute('target', '_blank')
    await expect(externalLink).toHaveAttribute('href', /nota-/)

    // The first fake note carries the "minimalista" tag, so the seeded garment
    // (same tag) must appear in its related garments section.
    await expect(notes.getByRole('img', { name: garmentName })).toBeVisible()
  } finally {
    // Leave the shared content hash free for the outfits spec, which seeds its
    // own garment from the same fixture.
    await archiveGarment(request, garmentId)
  }
})
