import { expect, test } from '@playwright/test'
import type { APIRequestContext } from '@playwright/test'
import {
  API_URL,
  findGarmentByName,
  seedGarment as createGarment,
} from './helpers/seed'

const ADMIN_SECRET = 'test-secret'

interface GarmentSeed {
  fixture: string
  name: string
  styleTags: string[]
}

/**
 * Creates a digest test garment with manual attributes. A retry can find the
 * row from its previous attempt (the endpoint returns 409), so the helper
 * falls back to the existing row by name.
 */
async function seedGarment(
  request: APIRequestContext,
  seed: GarmentSeed,
): Promise<string> {
  try {
    const { garment } = await createGarment(request, {
      fixture: seed.fixture,
      name: seed.name,
      category: 'top',
      colorName: 'beige',
      styleTags: seed.styleTags.join(','),
    })
    return garment.id
  } catch {
    const existing = await findGarmentByName(request, seed.name)
    if (!existing) throw new Error(`No se pudo sembrar ${seed.name}.`)
    return existing.id
  }
}

test('muestra el resumen del día y lo relaciona con una prenda', async ({
  page,
  request,
}) => {
  // Unique per attempt: a CI retry reuses the isolated database and would
  // otherwise find two garments with the same name (ambiguous locator).
  const suffix = `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`
  const garmentName = `Camisa de lino ${suffix}`

  await seedGarment(request, {
    fixture: 'camisa-hex.jpg',
    name: garmentName,
    styleTags: ['capas'],
  })

  const refresh = await request.post(`${API_URL}/api/digest/refresh`, {
    headers: { 'X-Admin-Secret': ADMIN_SECRET },
  })

  // A retry runs within the one-hour cooldown: the digest generated by the
  // failed first attempt is still valid and serves the same notes.
  expect([200, 429]).toContain(refresh.status())

  await page.goto('/')

  await expect(page.getByRole('heading', { name: 'Hoy' })).toBeVisible()
  await expect(page.getByText(/novedades de moda para hoy/i)).toBeVisible()

  const notes = page.getByRole('list', { name: 'Novedades del día' })
  const externalLink = notes.getByRole('link').first()
  await expect(externalLink).toHaveAttribute('target', '_blank')
  await expect(externalLink).toHaveAttribute('href', /^https:\/\/www\.(vogue|elle|harpersbazaar|glamour|gq)\.com\//)

  // The first note carries the "capas" tag, so the seeded garment must appear
  // in its related garments section.
  await expect(notes.getByRole('img', { name: garmentName }).first()).toBeVisible()
})
