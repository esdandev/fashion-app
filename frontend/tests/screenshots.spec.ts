async function seedOutfits(
  request: APIRequestContext,
  garmentIds: Map<string, string>,
) {
  const existing = await request.get(`${API_URL}/api/outfits`)
  expect(existing.ok()).toBeTruthy()
  const outfits = (await existing.json()) as Array<{ id: string }>
  if (outfits.length > 0) {
    return
  }

  for (const outfit of OUTFITS) {
    const garmentIdsForOutfit = outfit.files.map((file) => {
      const id = garmentIds.get(file)
      if (!id) {
        throw new Error(`Falta la prenda sembrada ${file}`)
      }
      return id
    })

    const created = await request.post(`${API_URL}/api/outfits`, {
      data: {
        name: outfit.name,
        occasion: outfit.occasion,
        garmentIds: garmentIdsForOutfit,
        source: 'ai',
        rationale: outfit.rationale,
      },
    })

    if (!created.ok()) {
      throw new Error(
        `No se pudo crear el outfit ${outfit.name}: ${created.status()} ${await created.text()}`,
      )
    }
  }
}

async function waitForImages(page: Page) {
  // Cards below the fold use loading="lazy" and never start downloading while
  // they stay out of the viewport, so only the images that intersect it are
  // part of the screenshot and must be complete.
  await page.waitForFunction(() => {
    const viewportHeight = window.innerHeight
    return Array.from(document.images).every((image) => {
      if (!image.getAttribute('src') || image.complete) {
        return true
      }

      const rect = image.getBoundingClientRect()
      return rect.top >= viewportHeight || rect.bottom <= 0
    })
  })
}

interface Capture {
  name: string
  path: string
  /**
   * Hoy needs more vertical room so the "En tu guardarropa" strip of the first
   * card is not clipped. The other pages keep the standard viewport.
   */
  desktopHeight?: number
  mobileHeight?: number
  ready: (page: Page) => Promise<void>
}

const CAPTURES: Capture[] = [
  {
    name: 'hoy',
    path: '/',
    desktopHeight: 1100,
    mobileHeight: 1050,
    ready: (page: Page) =>
      expect(page.getByRole('heading', { name: 'Hoy' })).toBeVisible(),
  },
  {
    name: 'guardarropa',
    path: '/guardarropa',
    ready: (page: Page) =>
      expect(page.getByText(/prendas cargadas/)).toBeVisible(),
  },
  {
    name: 'outfits',
    path: '/outfits',
    ready: (page: Page) =>
      expect(page.getByText(/outfits guardados/)).toBeVisible(),
  },
]

const VIEWPORTS = [
  {
    suffix: 'desktop',
    viewport: { width: 1440, height: 900 },
    deviceScaleFactor: 1,
    isMobile: false,
    hasTouch: false,
  },
  {
    suffix: 'mobile',
    viewport: { width: 390, height: 844 },
    deviceScaleFactor: 2,
    isMobile: true,
    hasTouch: true,
  },
] as const

async function captureAll(browser: Browser) {
  mkdirSync(screenshotsDir, { recursive: true })

  for (const viewport of VIEWPORTS) {
    const context = await browser.newContext({
      viewport: viewport.viewport,
      deviceScaleFactor: viewport.deviceScaleFactor,
      isMobile: viewport.isMobile,
      hasTouch: viewport.hasTouch,
      locale: 'es-AR',
    })
    const page = await context.newPage()

    for (const capture of CAPTURES) {
      const height =
        viewport.suffix === 'desktop'
          ? (capture.desktopHeight ?? viewport.viewport.height)
          : (capture.mobileHeight ?? viewport.viewport.height)
      await page.setViewportSize({ width: viewport.viewport.width, height })
      await page.goto(capture.path)
      await capture.ready(page)
      await page.waitForLoadState('networkidle')
      await page.evaluate(() => document.fonts.ready)
      await waitForImages(page)

      await page.screenshot({
        path: join(screenshotsDir, `${capture.name}-${viewport.suffix}.png`),
        fullPage: false,
      })
    }

    await context.close()
  }
}

test.skip(process.env.CAPTURE !== '1', 'capturas manuales (CAPTURE=1)')

test('captura Hoy, Guardarropa y Outfits en desktop y mobile', async ({
  browser,
  request,
}) => {
  test.setTimeout(600_000)

  const garmentIds = await seedWardrobe(request)
  await seedDigest(request)
  await seedOutfits(request, garmentIds)

  await captureAll(browser)
})
