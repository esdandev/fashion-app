import { mkdirSync, readFileSync } from 'node:fs'
import { dirname, extname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { expect, test } from '@playwright/test'
import type { APIRequestContext, Browser, Page } from '@playwright/test'

/**
 * Manual portfolio captures. They never run in the normal suite or in CI: the
 * spec is skipped unless CAPTURE=1, so a regular `pnpm exec playwright test`
 * keeps the isolated database untouched and fast.
 *
 * Usage (from `frontend/`):
 *
 *   CAPTURE=1 pnpm exec playwright test tests/screenshots.spec.ts
 *   # PowerShell: $env:CAPTURE='1'; pnpm exec playwright test tests/screenshots.spec.ts
 *
 * The spec talks to the isolated Playwright backend (`.test-data`, fake AI and
 * fake feeds) to seed a rich wardrobe, one digest and a couple of outfits, then
 * saves three pages in desktop and mobile viewports under `docs/screenshots/`.
 */

const API_URL = 'http://localhost:5210'
const ADMIN_SECRET = 'test-secret'
const repoDir = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const screenshotsDir = join(repoDir, 'docs', 'screenshots')
const demoAssetsDir = join(
  repoDir,
  'backend',
  'FashionApp.Api',
  'Infrastructure',
  'Demo',
  'SeedAssets',
)
const manifestPath = join(demoAssetsDir, 'manifest.json')

interface ManifestItem {
  name: string
  category: 'Top' | 'Bottom' | 'Dress' | 'Outerwear' | 'Shoes' | 'Bag' | 'Accessory'
  colorName: string
  colorHex: string
  seasons: string[]
  formality: number
  styleTags: string[]
  file: string
}

interface Manifest {
  items: ManifestItem[]
}

/**
 * Reuses the demo manifest (names, colors, seasons, tags and placeholder WebP
 * images) instead of duplicating fifteen fixtures in the spec. The UI then
 * looks like the deployed demo, which is exactly what the portfolio needs.
 *
 * The file is read inside the test, not at module load: if the manifest moves,
 * the skipped spec must not break collection of the rest of the suite.
 */
function loadManifest(): Manifest {
  return JSON.parse(readFileSync(manifestPath, 'utf8')) as Manifest
}

async function seedGarment(
  request: APIRequestContext,
  item: ManifestItem,
): Promise<string> {
  const extension = extname(item.file).toLowerCase()
  const mimeType = extension === '.webp' ? 'image/webp' : 'image/jpeg'

  const analyze = await request.post(`${API_URL}/api/garments/analyze`, {
    multipart: {
      file: {
        name: item.file,
        mimeType,
        buffer: readFileSync(join(demoAssetsDir, item.file)),
      },
    },
  })

  if (!analyze.ok()) {
    throw new Error(
      `No se pudo analizar ${item.file}: ${analyze.status()} ${await analyze.text()}`,
    )
  }

  const { contentHash } = (await analyze.json()) as { contentHash: string }

  // Confirm is idempotent by content hash: a second manual run returns the row
  // stored by the first one instead of creating a duplicate.
  const confirm = await request.post(`${API_URL}/api/garments/confirm`, {
    data: {
      contentHash,
      name: item.name,
      category: item.category,
      colorName: item.colorName,
      colorHex: item.colorHex,
      seasons: item.seasons,
      formality: item.formality,
      styleTags: item.styleTags,
      confidence: 0.95,
    },
  })

  if (!confirm.ok()) {
    throw new Error(
      `No se pudo confirmar ${item.name}: ${confirm.status()} ${await confirm.text()}`,
    )
  }

  const { garment } = (await confirm.json()) as { garment: { id: string } }
  return garment.id
}

async function seedWardrobe(
  request: APIRequestContext,
): Promise<Map<string, string>> {
  const manifest = loadManifest()
  const ids = new Map<string, string>()
  for (const item of manifest.items) {
    ids.set(item.file, await seedGarment(request, item))
  }

  return ids
}

async function seedDigest(request: APIRequestContext) {
  const refresh = await request.post(`${API_URL}/api/digest/refresh`, {
    headers: { 'X-Admin-Secret': ADMIN_SECRET },
  })

  // A manual rerun within the one-hour cooldown keeps the digest generated by
  // the previous run, which is all the captures need.
  expect([200, 429]).toContain(refresh.status())
}

